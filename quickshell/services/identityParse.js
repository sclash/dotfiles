// fprintd finger ids (utils/fprintd-enroll.c, fprintd 1.94.5).
const FINGERS = [
    "left-thumb", "left-index-finger", "left-middle-finger", "left-ring-finger", "left-little-finger",
    "right-thumb", "right-index-finger", "right-middle-finger", "right-ring-finger", "right-little-finger"
]

// fprintd-list prints " - #N: <finger>" per enrolled finger (utils/list.c).
// Returns the known finger ids, deduplicated.
function parseEnrolled(text) {
    const out = []
    const re = /^\s*-\s*#\d+:\s*(\S+)\s*$/gm
    let m
    while ((m = re.exec(text || "")) !== null) {
        if (FINGERS.indexOf(m[1]) !== -1 && out.indexOf(m[1]) === -1)
            out.push(m[1])
    }
    return out
}

// Classifies fprintd-list output. "" = usable output; otherwise a distinct
// degraded state (utils/list.c messages).
function listError(text) {
    const t = (text || "").toLowerCase()
    if (t.indexOf("no devices available") !== -1) return "nodevice"
    if (t.indexOf("impossible to get devices") !== -1
        || t.indexOf("failed to connect to session bus") !== -1
        || t.indexOf("failed to get fprintd manager") !== -1) return "daemon"
    if (t.indexOf("listenrolledfingers failed") !== -1) return "listfail"
    return ""
}

// ---------- per-user choices and the hyprlock override ----------

const METHODS = ["fingerprint", "face"]

// ~/.local/state/identity/choices: one `method=on|off` per line, last wins.
// "" (key missing, file absent, garbage) = follow the hardware default.
function parseChoices(text) {
    const out = { fingerprint: "", face: "" }
    const re = /^\s*(\w+)\s*=\s*(on|off)\s*$/gm
    let m
    while ((m = re.exec(text || "")) !== null) {
        if (METHODS.indexOf(m[1]) !== -1) out[m[1]] = m[2]
    }
    return out
}

function renderChoices(choices) {
    return METHODS.filter(k => choices[k] === "on" || choices[k] === "off")
        .map(k => k + "=" + choices[k] + "\n").join("")
}

// "unavailable" without the hardware, otherwise the user's choice, with
// "enabled" as the default when the hardware is present.
function methodState(present, choice) {
    if (!present) return "unavailable"
    return choice === "off" ? "disabled" : "enabled"
}

// What hyprlock should actually do. Face needs the IR camera, the user's
// consent (default yes) and at least one face model; without a model Howdy
// could only fail, so the password-only PAM service is used instead.
function effectiveAuth(s) {
    const fingerprint = methodState(s.fingerprintPresent, s.fingerprintChoice) === "enabled"
    const face = methodState(s.irPresent, s.faceChoice) === "enabled" && s.faceModelCount > 0
    return { fingerprint: fingerprint, face: face, pamModule: face ? "hyprlock-face" : "hyprlock" }
}

// Lock-screen method icons: [{ method, look }] in display order, where look
// is "selected" (the method hyprlock tries first), "enabled" (works, the
// fallback) or "disabled" (supported but off); unsupported ones are left
// out. Fingerprint comes first when usable; face needs at least one model.
function lockIcons(s) {
    const out = []
    const fpOn = s.fingerprintState === "enabled"
    const faceOn = s.faceState === "enabled" && s.faceModelCount > 0
    const primary = fpOn ? "fingerprint" : (faceOn ? "face" : "")
    if (s.fingerprintState !== "unavailable")
        out.push({ method: "fingerprint", look: fpOn ? (primary === "fingerprint" ? "selected" : "enabled") : "disabled" })
    if (s.faceState !== "unavailable")
        out.push({ method: "face", look: faceOn ? (primary === "face" ? "selected" : "enabled") : "disabled" })
    return out
}

function _label(text, color, size, x, y, font) {
    return "label {\n"
        + "    monitor =\n"
        + "    text = " + text + "\n"
        + "    color = rgb(" + color + ")\n"
        + "    font_size = " + size + "\n"
        + "    font_family = " + font + "\n"
        + "    position = " + x + ", " + y + "\n"
        + "    halign = center\n"
        + "    valign = center\n"
        + "}\n"
}

// ~/.local/state/hyprlock-auth.conf, sourced last by hypr/hyprlock.conf:
// the auth switches plus the method icons under the password box and a
// one-line hint. `style` = { glyphs: { fingerprint, face }, colors:
// { selected, enabled, disabled, hint } (hex, no #), font }, from Theme/Icons.
// hyprlock starts PAM (face) only when Enter is pressed.
function renderHyprlockAuth(e, icons, style) {
    let t = "# Generated by the Quickshell Identity Manager (SUPER+I). Do not edit:\n"
        + "# it is rewritten from ~/.local/state/identity/choices on every change.\n"
        + "auth {\n"
        + "    fingerprint {\n        enabled = " + (e.fingerprint ? "true" : "false") + "\n    }\n"
        + "    pam {\n        module = " + e.pamModule + "\n    }\n"
        + "}\n"
    const list = icons || []
    if (list.length === 0 || !style) return t
    const gap = 44
    list.forEach((ic, i) => {
        const x = Math.round((i - (list.length - 1) / 2) * gap)
        t += _label(style.glyphs[ic.method], style.colors[ic.look], 20, x, -265, style.font)
    })
    const look = m => (list.find(i => i.method === m) || {}).look || ""
    let hint = ""
    if (look("fingerprint") === "selected")
        hint = look("face") === "enabled" ? "Touch the sensor · or Enter for face" : "Touch the sensor to unlock"
    else if (look("face") === "selected")
        hint = "Press Enter to unlock with your face"
    if (hint !== "") t += _label(hint, style.colors.hint || style.colors.enabled, 10, 0, -300, style.font)
    return t
}

// ---------- Howdy (face) ----------

// device_path from the [video] section of /etc/howdy/config.ini; "" if none.
function parseHowdyDevicePath(text) {
    let section = ""
    let out = ""
    for (const raw of String(text || "").split("\n")) {
        const line = raw.trim()
        const sec = line.match(/^\[(.+)\]$/)
        if (sec) { section = sec[1].trim(); continue }
        const kv = line.match(/^device_path\s*=\s*(.*)$/)
        if (kv && section === "video") out = kv[1].trim()
    }
    return out
}

// /var/lib/howdy/models/<user>.dat is a JSON array of
// { time, label, id, data }; the face encodings (data) are dropped.
function parseHowdyModels(text) {
    let arr
    try { arr = JSON.parse(text) } catch (e) { return [] }
    if (!Array.isArray(arr)) return []
    return arr.filter(m => m && typeof m.id === "number")
        .map(m => ({ id: m.id, label: String(m.label || ""), time: Number(m.time) || 0 }))
}

// Last meaningful line of `howdy add/remove` output, plus whether it points
// at a dark IR emitter (cli/add.py messages, Howdy 3.0.0).
function howdyMessage(text) {
    const lines = String(text || "").split("\n").map(l => l.trim()).filter(l => l !== "")
    const last = lines.length ? lines[lines.length - 1] : ""
    return { text: last, needsEmitter: /black frames|IR emitter/i.test(String(text || "")) }
}

// Why `pkexec howdy …` never ran (exit 126/127, polkit 127 messages);
// "" when pkexec did run the command and any failure is Howdy's own.
function pkexecMessage(code, text) {
    if (code !== 126 && code !== 127) return ""
    const t = String(text || "")
    if (/no authentication agent/i.test(t)) return "No password prompt available (polkit agent not running)"
    if (/dismissed/i.test(t)) return "Authorization cancelled"
    if (/not authorized/i.test(t)) return "Authorization failed"
    return "Authorization cancelled or failed"
}

// ---------- password (identity-passwd) ----------

// One result line from quickshell/scripts/identity-passwd.py.
function passwdResult(line) {
    const l = String(line || "").trim()
    if (l === "OK") return { ok: true, message: "Password changed" }
    if (l === "BAD_CURRENT") return { ok: false, message: "Current password is wrong" }
    if (l.indexOf("REJECTED") === 0) return { ok: false, message: "Rejected: " + l.slice(9).trim() }
    if (l.indexOf("ERROR") === 0) return { ok: false, message: "Error: " + l.slice(6).trim() }
    return { ok: false, message: "Error: no answer from identity-passwd" }
}

// Checks the password form before anything is sent to passwd. Returns ""
// when the form may be submitted, otherwise the message shown under it.
// The first three checks are not optional: a mistyped new password must
// never reach passwd. passwd/PAM still has the final word on the rest.
function validatePasswordForm(current, next, confirm) {
    if (current === "") return "Enter your current password"
    if (next === "") return "Enter a new password"
    if (next !== confirm) return "The new passwords do not match"
    return passwordPolicy(current, next)
}

// Extra rules the form enforces before passwd sees the new password.
// Return "" to accept, or the message to show. Deliberately no length or
// character limits: only leading/trailing whitespace, which is easy to type
// by accident and invisible later.
function passwordPolicy(current, next) {
    if (/^\s|\s$/.test(next)) return "The new password starts or ends with a space"
    return ""
}

