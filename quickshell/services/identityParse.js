// "right-index-finger" -> "Right Index Finger"; unknown names pass through.
function fingerLabel(name) {
    if (FINGERS.indexOf(name) === -1) return name
    return name.split("-").map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(" ")
}
